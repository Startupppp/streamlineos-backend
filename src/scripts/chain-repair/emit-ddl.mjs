const BREAK = "--> statement-breakpoint";

export function ident(name) {
  return `"${String(name).replace(/"/g, '""')}"`;
}

export function qualify(schema, name) {
  return `${ident(schema)}.${ident(name)}`;
}

export function literal(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

export function guarded(existsQuery, body) {
  return `DO $repair$ BEGIN\n  IF NOT EXISTS (${existsQuery}) THEN\n    ${body};\n  END IF;\nEND $repair$;`;
}

export function createType(type, labels) {
  const ordered = labels
    .slice()
    .sort((a, b) => a.ord - b.ord)
    .map((l) => literal(l.label))
    .join(", ");
  return guarded(
    `SELECT 1 FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace` +
      ` WHERE n.nspname = ${literal(type.schema)} AND t.typname = ${literal(type.name)}`,
    `CREATE TYPE ${qualify(type.schema, type.name)} AS ENUM (${ordered})`,
  );
}

export function columnClause(column) {
  const parts = [ident(column.name), column.type];
  if (column.collation) parts.push(`COLLATE ${ident(column.collation)}`);
  if (column.identity === "a") parts.push("GENERATED ALWAYS AS IDENTITY");
  else if (column.identity === "d") parts.push("GENERATED BY DEFAULT AS IDENTITY");
  else if (column.generated === "s" && column.defaultExpr)
    parts.push(`GENERATED ALWAYS AS (${column.defaultExpr}) STORED`);
  else if (column.defaultExpr !== null) parts.push(`DEFAULT ${column.defaultExpr}`);
  if (column.notnull) parts.push("NOT NULL");
  return parts.join(" ");
}

export class UnsupportedTableShapeError extends Error {
  constructor(table, reason) {
    super(`${table.schema}.${table.name}: ${reason}`);
    this.name = "UnsupportedTableShapeError";
  }
}

export function createSchema(schema) {
  return `CREATE SCHEMA IF NOT EXISTS ${ident(schema.name)};`;
}

export function createTable(table, columns) {
  if (table.kind === "p")
    throw new UnsupportedTableShapeError(
      table,
      "partitioned parent. Emitting it as a plain table would silently drop the partition key" +
        " and every partition. Add PARTITION BY support before regenerating.",
    );
  if (table.parent !== null && table.parent !== undefined)
    throw new UnsupportedTableShapeError(
      table,
      `partition of ${table.parent}. Emitting it as a standalone table would detach it from its` +
        " parent. Add PARTITION OF support before regenerating.",
    );
  const body = columns
    .slice()
    .sort((a, b) => a.ord - b.ord)
    .map((c) => `  ${columnClause(c)}`)
    .join(",\n");
  return `CREATE TABLE IF NOT EXISTS ${qualify(table.schema, table.name)} (\n${body}\n);`;
}

export function addColumn(column) {
  const parts = [ident(column.name), column.type];
  if (column.collation) parts.push(`COLLATE ${ident(column.collation)}`);
  if (column.identity === "a") parts.push("GENERATED ALWAYS AS IDENTITY");
  else if (column.identity === "d") parts.push("GENERATED BY DEFAULT AS IDENTITY");
  else if (column.generated === "s" && column.defaultExpr)
    parts.push(`GENERATED ALWAYS AS (${column.defaultExpr}) STORED`);
  else if (column.defaultExpr !== null) parts.push(`DEFAULT ${column.defaultExpr}`);
  const add = `ALTER TABLE ${qualify(column.schema, column.table)} ADD COLUMN IF NOT EXISTS ${parts.join(" ")};`;
  if (!column.notnull) return add;
  const setNotNull = guarded(
    `SELECT 1 FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid` +
      ` JOIN pg_namespace n ON n.oid = c.relnamespace` +
      ` WHERE n.nspname = ${literal(column.schema)} AND c.relname = ${literal(column.table)}` +
      ` AND a.attname = ${literal(column.name)} AND a.attnotnull`,
    `ALTER TABLE ${qualify(column.schema, column.table)} ALTER COLUMN ${ident(column.name)} SET NOT NULL`,
  );
  return `${add}\n${BREAK}\n${setNotNull}`;
}

export function alterColumnType(column) {
  return (
    `ALTER TABLE ${qualify(column.schema, column.table)}` +
    ` ALTER COLUMN ${ident(column.name)} TYPE ${column.type}` +
    ` USING ${ident(column.name)}::${column.type};`
  );
}

export function createFunction(fn) {
  if (fn.def === null) return null;
  const def = fn.def.replace(/^CREATE FUNCTION/i, "CREATE OR REPLACE FUNCTION");
  return def.trimEnd().endsWith(";") ? def : `${def};`;
}

export function addConstraint(constraint) {
  return guarded(
    `SELECT 1 FROM pg_constraint k JOIN pg_class c ON c.oid = k.conrelid` +
      ` JOIN pg_namespace n ON n.oid = c.relnamespace` +
      ` WHERE n.nspname = ${literal(constraint.schema)} AND c.relname = ${literal(constraint.table)}` +
      ` AND k.conname = ${literal(constraint.name)}`,
    `ALTER TABLE ${qualify(constraint.schema, constraint.table)}` +
      ` ADD CONSTRAINT ${ident(constraint.name)} ${constraint.def}`,
  );
}

export function createIndex(index) {
  const withExists = index.def
    .replace(/^CREATE INDEX /i, "CREATE INDEX IF NOT EXISTS ")
    .replace(/^CREATE UNIQUE INDEX /i, "CREATE UNIQUE INDEX IF NOT EXISTS ");
  return withExists.trimEnd().endsWith(";") ? withExists : `${withExists};`;
}

export function createTrigger(trigger) {
  return guarded(
    `SELECT 1 FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid` +
      ` JOIN pg_namespace n ON n.oid = c.relnamespace` +
      ` WHERE n.nspname = ${literal(trigger.schema)} AND c.relname = ${literal(trigger.table)}` +
      ` AND t.tgname = ${literal(trigger.name)}`,
    trigger.def,
  );
}

export function enableRls(table) {
  return `ALTER TABLE ${qualify(table.schema, table.name)} ENABLE ROW LEVEL SECURITY;`;
}

export function createPolicy(policy) {
  const roles = policy.roles.length > 0 ? policy.roles.map((r) => ident(r)).join(", ") : "PUBLIC";
  const parts = [
    `CREATE POLICY ${ident(policy.name)} ON ${qualify(policy.schema, policy.table)}`,
    `AS ${policy.permissive === "PERMISSIVE" ? "PERMISSIVE" : "RESTRICTIVE"}`,
    `FOR ${policy.cmd}`,
    `TO ${roles}`,
  ];
  if (policy.qual !== null) parts.push(`USING (${policy.qual})`);
  if (policy.withCheck !== null) parts.push(`WITH CHECK (${policy.withCheck})`);
  return guarded(
    `SELECT 1 FROM pg_policies WHERE schemaname = ${literal(policy.schema)}` +
      ` AND tablename = ${literal(policy.table)} AND policyname = ${literal(policy.name)}`,
    parts.join(" "),
  );
}

export function grantAppRole(table, role) {
  return (
    `REVOKE ALL ON ${qualify(table.schema, table.name)} FROM PUBLIC;\n${BREAK}\n` +
    `GRANT SELECT, INSERT, UPDATE, DELETE ON ${qualify(table.schema, table.name)} TO ${ident(role)};`
  );
}

export function section(title) {
  return `--\n-- ${title}\n--`;
}

export function join(statements) {
  return statements.filter((s) => s !== null && s !== "").join(`\n${BREAK}\n`);
}
